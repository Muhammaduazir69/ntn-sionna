#!/usr/bin/env python3
"""Write ../macros_p9.tex from out/: every number of the manuscript."""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "out")
TAG = {"munich": "Mun", "etoile": "Par", "florence": "Flo", "san_francisco": "Sfo"}
M = {}


def f(x, d=1):
    return f"{x:.{d}f}"


A = json.load(open(os.path.join(OUT, "analysis.json")))
F = json.load(open(os.path.join(OUT, "models.json")))
S = json.load(open(os.path.join(OUT, "city_stats.json")))
V = json.load(open(os.path.join(OUT, "validate_screen.json")))
TR = A["tr38811"]
els = np.array(A["munich"]["els"])
M["NUsers"] = str(A["munich"]["n_users"])
los_exc_med, los_exc_max, unr = [], [], []
for c, t in TAG.items():
    a, m, s = A[c], F[c], S[c]
    for e in (15, 30, 45, 60):
        i = list(els).index(e)
        M[f"Los{t}E{['','','','Fifteen','','','Thirty','','','FortyFive','','','Sixty'][e // 5]}"] = f(100 * a["los"][i], 0)
    M[f"LosAlong{t}"], M[f"LosAcross{t}"] = f(100 * m["los30_along"], 0), f(100 * m["los30_across"], 0)
    M[f"RuleAcc{t}"], M[f"RuleTwoAcc{t}"] = f(100 * m["rule_acc"], 1), f(100 * m["rule2_acc"], 1)
    M[f"ErrStat{t}"], M[f"ErrTrU{t}"], M[f"ErrTrD{t}"], M[f"ErrPit{t}"] = (f(100 * m[k], 0) for k in ("err_stat", "err_tr_urban", "err_tr_dense", "err_p1410"))
    nl = np.array([x if x is not None else np.nan for x in a["nlos_med"]])
    M[f"NlosLo{t}"], M[f"NlosHi{t}"] = f(np.nanmin(nl), 0), f(np.nanmax(nl), 0)
    M[f"Width{t}"] = f(np.median(np.load(os.path.join(OUT, f"street_{c}.npz"))["width_m"]), 0)
    M[f"Hmed{t}"], M[f"Alpha{t}"] = f(s["h_median"], 0), f(100 * s["alpha"], 0)
    los_exc_med += [x for x in a["los_exc_med"]]; unr.append(a["unreached_share"])
    lo = F["loss_loo"][c]
    M[f"LooMean{t}"], M[f"LooMax{t}"] = f(lo["mean_err"], 1), f(lo["max_err"], 1)
M["LosExcMed"] = f(np.median(los_exc_med), 1)
M["LosExcMax"] = f(np.max(np.abs(los_exc_med)), 1)
M["UnreachedShare"] = f(100 * np.mean(unr), 1)
M["UnreachedLo"], M["UnreachedHi"] = f(100 * min(unr), 1), f(100 * max(unr), 1)
nu = np.array(V["nu"]); sd = np.array(V["sionna_db"]); kd = np.array(V["knife_db"]); sh = nu > 1
M["ScreenDiffLo"], M["ScreenDiffHi"] = f(-np.max(sd[sh] - kd[sh]), 1), f(-np.min(sd[sh] - kd[sh]), 1)
M["ScreenDiffMed"] = f(-np.median(sd[sh] - kd[sh]), 1)
M["LossA"], M["LossB"] = f(F["loss_fit_all"]["a"], 1), f(F["loss_fit_all"]["b"], 1)
M["RuleAccMin"] = f(100 * min(F[c]["rule_acc"] for c in TAG), 1)
M["RuleTwoAccMin"] = f(100 * min(F[c]["rule2_acc"] for c in TAG), 1)
M["ErrStatMaxFlat"] = f(100 * max(F[c]["err_stat"] for c in ("munich", "etoile", "florence")), 0)
M["ErrTrMin"] = f(100 * min(min(F[c]["err_tr_urban"], F[c]["err_tr_dense"]) for c in TAG), 0)
M["ErrTrMax"] = f(100 * max(max(F[c]["err_tr_urban"], F[c]["err_tr_dense"]) for c in TAG), 0)
M["LooMeanLo"] = f(min(F["loss_loo"][c]["mean_err"] for c in TAG), 1)
M["LooMeanHi"] = f(max(F["loss_loo"][c]["mean_err"] for c in TAG), 1)
cl = np.array(TR["cl_s"]["dense_urban"])
M["TrClLo"], M["TrClHi"] = f(cl.min(), 1), f(cl.max(), 1)
allnl = np.concatenate([[x for x in A[c]["nlos_med"] if x is not None] for c in TAG])
M["NlosAllLo"], M["NlosAllHi"] = f(allnl.min(), 0), f(allnl.max(), 0)
# sensitivity (Munich, 60 users)
sens = {}
for tag, nm in (("_base", "Base"), ("_d5", "DepthFive"), ("_d7", "DepthSeven"), ("_d9", "DepthNine"),
                ("_s4", "Samples"), ("_s10", "SamplesTen"), ("_sc4", "Scatter"), ("_nr", "NoReflect")):
    p = os.path.join(OUT, f"sky_munich{tag}.npz")
    if os.path.exists(p):
        z = np.load(p); los, exc = z["los"], z["exc"]
        if los.shape[0] < 60:
            continue   # run still in progress
        xa = -exc[~los]; x = xa[xa < 150]
        sens[nm] = np.median(x)
        M[f"SensPninety{nm}"] = f(np.percentile(x, 90), 0)
        M[f"SensUnr{nm}"] = f(100 * np.mean(xa >= 150), 1)
if "Base" in sens:
    for nm, v in sens.items():
        M[f"Sens{nm}"] = f(v, 1)
    M["SensMaxShift"] = f(max(abs(v - sens["Base"]) for k, v in sens.items() if k != "NoReflect"), 1)
with open(os.path.join(HERE, "..", "macros_p9.tex"), "w") as fh:
    fh.write("% generated by sim/make_macros.py; do not edit\n")
    for k, v in sorted(M.items()):
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(len(M), "macros")
kb = [F[c]["knife_bias"] for c in TAG]
with open(os.path.join(HERE, "..", "macros_p9.tex"), "a") as fh:
    fh.write(f"\\newcommand{{\\KnifeBiasLo}}{{{min(kb):.0f}}}\n\\newcommand{{\\KnifeBiasHi}}{{{max(kb):.0f}}}\n")
    for c, t in TAG.items():
        fh.write(f"\\newcommand{{\\KnifeBias{t}}}{{{F[c]['knife_bias']:.0f}}}\n")
with open(os.path.join(HERE, "..", "macros_p9.tex"), "a") as fh:
    for c, t in TAG.items():
        fh.write(f"\\newcommand{{\\ErrCanyon{t}}}{{{100 * F[c]['err_canyon']:.0f}}}\n")
        a, b = F[c]["los30_along_ci"], F[c]["los30_across_ci"]
        fh.write(f"\\newcommand{{\\LosAlongCi{t}}}{{{100 * a[0]:.0f}--{100 * a[1]:.0f}}}\n\\newcommand{{\\LosAcrossCi{t}}}{{{100 * b[0]:.0f}--{100 * b[1]:.0f}}}\n")
    flat = [F[c]["err_canyon"] for c in ("munich", "etoile", "florence")]
    fh.write(f"\\newcommand{{\\ErrCanyonFlatLo}}{{{100 * min(flat):.0f}}}\n\\newcommand{{\\ErrCanyonFlatHi}}{{{100 * max(flat):.0f}}}\n")
    fh.write(f"\\newcommand{{\\LosCiMax}}{{{100 * max(F[c]['los_ci_halfwidth_max'] for c in TAG):.1f}}}\n")
